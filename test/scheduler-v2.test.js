"use strict";
const assert=require('assert');
const C=require('../scheduler-core.js');
function eq(a,b,msg){assert.deepStrictEqual(a,b,msg)}
eq(C.profile('2026-08-12').wake,300,'Wednesday wake 05:00');
eq(C.profile('2026-08-12').end,1260,'Wednesday end 21:00');
eq(C.profile('2026-08-14').end,1080,'Friday cutoff 18:00');
eq(C.profile('2026-08-15').end,720,'Saturday cutoff 12:00');
eq(C.profile('2026-08-16').end,1320,'Sunday personal day remains available');
assert.equal(C.domainAllowed('GSA','2026-08-16'),false,'Sunday blocks GSA');
assert.equal(C.domainAllowed('Estudos','2026-08-16'),false,'Sunday blocks study');
assert.equal(C.domainAllowed('Pessoal','2026-08-16'),true,'Sunday permits personal activities');
assert.equal(C.domainAllowed('GSA','2026-08-16',{weekendExtreme:true}),true,'Sunday extreme may open work');
assert.equal(C.bniTodayTarget('2026-08-10',0),60,'Monday spreads 120 min across remaining eligible days');
assert.equal(C.bniTodayTarget('2026-08-11',60),30,'Tuesday recalculates remaining BNI quota');
assert.equal(C.bniTodayTarget('2026-08-14',0),120,'Friday catches up entire remaining BNI quota');
const slots=[{key:'a',start:360,end:450},{key:'b',start:510,end:570}];
const g=C.nearestGap(slots,45,360,660,480);eq(g,{start:465,end:510},'nearest 45-min gap fits without overlap');
const valid=C.validatePlan({profile:{wake:360,end:660},slots:[...slots,{key:'c',start:465,end:510}]});assert(valid.ok,valid.errors.join(','));
const invalid=C.validatePlan({profile:{wake:360,end:660},slots:[{key:'a',start:360,end:450},{key:'x',start:440,end:470}]});assert(!invalid.ok,'overlap must fail validation');
assert.equal(C.emergencySleepAllowed(['2026-08-10'],'2026-08-11'),false,'never consecutive sleep emergency');
assert.equal(C.emergencySleepAllowed(['2026-08-04','2026-08-08'],'2026-08-10'),false,'max two in rolling seven days');
assert.equal(C.emergencySleepAllowed(['2026-08-04'],'2026-08-10'),true,'one recent exception still permits second');
const spread=C.spreadDates(['2026-08-10','2026-08-11','2026-08-12','2026-08-13','2026-08-14'],4,{'2026-08-12':9});
assert(spread.includes('2026-08-10'),'spread should use early days');
assert(spread.includes('2026-08-14'),'spread should use late days');
assert(spread.filter(x=>x==='2026-08-12').length===0,'heavily loaded midpoint should be avoided');
assert(/24h/.test(C.meaningfulReason({title:'Zerar leads sem resposta',category:'Vendas'})),'lead task should explain no-lead case');
assert(/sessão automática/i.test(C.meaningfulReason({title:'Avançar · Lattes do proponente',adaptiveSession:true})),'adaptive Avançar should be explained');
console.log('Scheduler 2.0 core tests passed');
